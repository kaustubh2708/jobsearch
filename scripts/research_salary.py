def evaluate_salary(company: str, target_min_base: float = 35.0) -> tuple[dict, str]:
    """Retrieve market compensation data and evaluate fit against Vrinda's 35 LPA base target."""
    now_str = datetime.now(timezone.utc).isoformat()
    data = SALARY_BENCHMARKS.get(company)

    if not data or not data["sources"]:
        est = {
            "currency": "INR",
            "base_lpa_low": None,
            "base_lpa_mid": None,
            "base_lpa_high": None,
            "total_comp_lpa_low": None,
            "total_comp_lpa_mid": None,
            "total_comp_lpa_high": None,
            "sources": [],
            "sample_size": None,
            "confidence": "low",
            "researched_at": now_str,
        }
        return est, "unknown"

    est = {
        "currency": "INR",
        "base_lpa_low": data["base_lpa_low"],
        "base_lpa_mid": data["base_lpa_mid"],
        "base_lpa_high": data["base_lpa_high"],
        "total_comp_lpa_low": data["total_comp_lpa_low"],
        "total_comp_lpa_mid": data["total_comp_lpa_mid"],
        "total_comp_lpa_high": data["total_comp_lpa_high"],
        "sources": data["sources"],
        "sample_size": data["sample_size"],
        "confidence": data["confidence"],
        "researched_at": now_str,
    }

    # Evaluate against 35 LPA target
    mid_base = data["base_lpa_mid"]
    high_base = data["base_lpa_high"]

    if mid_base >= target_min_base or (high_base and high_base >= target_min_base + 3):
        fit = "estimated"
    else:
        fit = "below_target"

    return est, fit


def main():
    salary_out = Path("data/salary_vrinda.json")
    database = {}
    now_str = datetime.now(timezone.utc).isoformat()

    for comp, info in SALARY_BENCHMARKS.items():
        database[comp] = {
            "currency": "INR",
            "base_lpa_low": info["base_lpa_low"],
            "base_lpa_mid": info["base_lpa_mid"],
            "base_lpa_high": info["base_lpa_high"],
            "total_comp_lpa_low": info["total_comp_lpa_low"],
            "total_comp_lpa_mid": info["total_comp_lpa_mid"],
            "total_comp_lpa_high": info["total_comp_lpa_high"],
            "sources": info["sources"],
            "sample_size": info["sample_size"],
            "confidence": info["confidence"],
            "meets_target_35_lpa": bool(info["base_lpa_mid"] >= 35.0),
            "researched_at": now_str,
            "notes": info["notes"],
        }

    salary_out.write_text(json.dumps(database, indent=2))
    print(f"Saved {len(database)} compensation benchmarks to {salary_out}")


if __name__ == "__main__":
    main()
